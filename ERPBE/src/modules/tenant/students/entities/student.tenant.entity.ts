import {
  Check,
  Column,
  CreateDateColumn,
  DeleteDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryGeneratedColumn,
  UpdateDateColumn,
} from 'typeorm';
import { Campus } from '../../organization/entities/campus.tenant.entity';
import { Person } from '../../people/entities/person.tenant.entity';
import { AdmissionKind, StudentStatus } from '../students.enums';

/** Student profile. Personal details live in persons; admission_no comes from next_code() in the DB. */
@Entity('students')
@Index('uq_students_person_live', { synchronize: false })
@Index('uq_students_admission_no_live', { synchronize: false })
@Index('uq_students_emis_id_live', { synchronize: false })
@Index('idx_students_status', ['status'])
@Index('idx_students_campus', ['campusId'])
@Check('chk_students_leaving_date', `leaving_date IS NULL OR leaving_date >= admission_date`)
export class Student {
  @PrimaryGeneratedColumn('uuid') id: string;
  @Column({ name: 'person_id', type: 'uuid' }) personId: string;
  @Column({ name: 'campus_id', type: 'uuid', nullable: true }) campusId: string | null;
  @Column({ name: 'emis_id', type: 'text', nullable: true }) emisId: string | null;
  /** Generated by the database; never sent by the application. */
  @Column({ name: 'admission_no', type: 'text', default: () => `next_code('admission_no')`, insert: false, update: false })
  admissionNo: string;
  @Column({ name: 'admission_date', type: 'date' }) admissionDate: string;
  @Column({ name: 'admission_type', type: 'enum', enum: AdmissionKind, enumName: 'admission_kind', default: AdmissionKind.NEW })
  admissionType: AdmissionKind;
  @Column({ name: 'previous_school_name', type: 'text', nullable: true }) previousSchoolName: string | null;
  @Column({ name: 'previous_school_class', type: 'text', nullable: true }) previousSchoolClass: string | null;
  @Column({ name: 'previous_tc_no', type: 'text', nullable: true }) previousTcNo: string | null;
  @Column({ name: 'has_special_needs', default: false }) hasSpecialNeeds: boolean;
  @Column({ type: 'enum', enum: StudentStatus, enumName: 'student_status', default: StudentStatus.ACTIVE }) status: StudentStatus;
  @Column({ name: 'leaving_date', type: 'date', nullable: true }) leavingDate: string | null;
  @Column({ name: 'leaving_reason', type: 'text', nullable: true }) leavingReason: string | null;
  @Column({ name: 'tc_issued_no', type: 'text', nullable: true }) tcIssuedNo: string | null;
  @Column({ type: 'text', nullable: true }) remarks: string | null;
  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' }) createdAt: Date;
  @UpdateDateColumn({ name: 'updated_at', type: 'timestamptz' }) updatedAt: Date;
  @Column({ name: 'created_by', type: 'uuid', nullable: true }) createdBy: string | null;
  @Column({ name: 'updated_by', type: 'uuid', nullable: true }) updatedBy: string | null;
  @DeleteDateColumn({ name: 'deleted_at', type: 'timestamptz' }) deletedAt: Date | null;

  @ManyToOne(() => Person)
  @JoinColumn({ name: 'person_id', foreignKeyConstraintName: 'fk_students_person' })
  person?: Person;

  @ManyToOne(() => Campus)
  @JoinColumn({ name: 'campus_id', foreignKeyConstraintName: 'fk_students_campus' })
  campus?: Campus | null;
}
