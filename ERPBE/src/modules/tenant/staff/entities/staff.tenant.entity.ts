import {
  Check,
  Column,
  CreateDateColumn,
  DeleteDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryGeneratedColumn,
  UpdateDateColumn,
} from 'typeorm';
import { Campus } from '../../organization/entities/campus.tenant.entity';
import { Department } from '../../organization/entities/department.tenant.entity';
import { Designation } from '../../organization/entities/designation.tenant.entity';
import { Person } from '../../people/entities/person.tenant.entity';
import { EmploymentKind, StaffKind, StaffStatus } from '../staff.enums';

/** Employee profile for every staff type; teacher/driver specifics live in extension tables. */
@Entity('staff')
@Index('uq_staff_person_live', { synchronize: false })
@Index('uq_staff_employee_code_live', { synchronize: false })
@Index('idx_staff_department', ['departmentId'])
@Index('idx_staff_campus', ['campusId'])
@Index('idx_staff_status', ['status'])
@Check('chk_staff_not_own_manager', `reports_to IS NULL OR reports_to <> id`)
@Check('chk_staff_leaving_date', `leaving_date IS NULL OR leaving_date >= joining_date`)
@Check('chk_staff_probation_end_date', `probation_end_date IS NULL OR probation_end_date >= joining_date`)
export class Staff {
  @PrimaryGeneratedColumn('uuid') id: string;
  @Column({ name: 'person_id', type: 'uuid' }) personId: string;
  @Column({ name: 'campus_id', type: 'uuid', nullable: true }) campusId: string | null;
  /** Generated by the database; never sent by the application. */
  @Column({ name: 'employee_code', type: 'text', default: () => `next_code('employee_code')`, insert: false, update: false })
  employeeCode: string;
  @Column({ name: 'staff_type', type: 'enum', enum: StaffKind, enumName: 'staff_kind' }) staffType: StaffKind;
  @Column({ name: 'department_id', type: 'uuid', nullable: true }) departmentId: string | null;
  @Column({ name: 'designation_id', type: 'uuid', nullable: true }) designationId: string | null;
  @Column({ name: 'reports_to', type: 'uuid', nullable: true }) reportsTo: string | null;
  @Column({ name: 'employment_type', type: 'enum', enum: EmploymentKind, enumName: 'employment_kind', nullable: true })
  employmentType: EmploymentKind | null;
  @Column({ name: 'joining_date', type: 'date' }) joiningDate: string;
  @Column({ name: 'probation_end_date', type: 'date', nullable: true }) probationEndDate: string | null;
  @Column({ name: 'leaving_date', type: 'date', nullable: true }) leavingDate: string | null;
  @Column({ name: 'leaving_reason', type: 'text', nullable: true }) leavingReason: string | null;
  @Column({ name: 'emergency_contact_name', type: 'text', nullable: true }) emergencyContactName: string | null;
  @Column({ name: 'emergency_contact_phone', type: 'text', nullable: true }) emergencyContactPhone: string | null;
  @Column({ type: 'enum', enum: StaffStatus, enumName: 'staff_status', default: StaffStatus.ACTIVE }) status: StaffStatus;
  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' }) createdAt: Date;
  @UpdateDateColumn({ name: 'updated_at', type: 'timestamptz' }) updatedAt: Date;
  @Column({ name: 'created_by', type: 'uuid', nullable: true }) createdBy: string | null;
  @Column({ name: 'updated_by', type: 'uuid', nullable: true }) updatedBy: string | null;
  @DeleteDateColumn({ name: 'deleted_at', type: 'timestamptz' }) deletedAt: Date | null;

  @ManyToOne(() => Person)
  @JoinColumn({ name: 'person_id', foreignKeyConstraintName: 'fk_staff_person' })
  person?: Person;

  @ManyToOne(() => Campus)
  @JoinColumn({ name: 'campus_id', foreignKeyConstraintName: 'fk_staff_campus' })
  campus?: Campus | null;

  @ManyToOne(() => Department)
  @JoinColumn({ name: 'department_id', foreignKeyConstraintName: 'fk_staff_department' })
  department?: Department | null;

  @ManyToOne(() => Designation)
  @JoinColumn({ name: 'designation_id', foreignKeyConstraintName: 'fk_staff_designation' })
  designation?: Designation | null;

  @ManyToOne(() => Staff)
  @JoinColumn({ name: 'reports_to', foreignKeyConstraintName: 'fk_staff_reports_to' })
  manager?: Staff | null;
}
